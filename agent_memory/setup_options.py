def country_code(name: str) -> str | None:
    """Restituisce il codice ISO di un paese, se il nome è in elenco."""

    return COUNTRY_CODE_BY_NAME.get(name.strip())


def italian_region(value: str) -> str | None:
    """Restituisce il nome canonico di una regione italiana, se in elenco."""

    folded = value.strip().casefold()
    if not folded:
        return None
    for region in ITALIAN_REGIONS:
        if region.casefold() == folded:
            return region
    return None


def italian_province(code: str) -> tuple[str, str] | None:
    """Restituisce (nome, regione) di una provincia italiana dalla sigla."""


def timezone_groups() -> list[tuple[str, list[str]]]:
    """Raggruppa i fusi orari IANA disponibili per area geografica."""

    grouped: dict[str, list[str]] = {}
    for zone in sorted(available_timezones()):
        if zone in _SKIPPED_TIMEZONES:
            continue
        region = zone.split("/", 1)[0] if "/" in zone else "Sigle e UTC"
        grouped.setdefault(region, []).append(zone)
    ordered = sorted(
        grouped.items(),
        key=lambda item: (item[0] == "Sigle e UTC", item[0]),
    )
    groups = [
        (TIMEZONE_REGIONS.get(region, region), zones)
        for region, zones in ordered
    ]
    if not groups:
        return [("Europa", ["Europe/Rome"])]
    return groups
